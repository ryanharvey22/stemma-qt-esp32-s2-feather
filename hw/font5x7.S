/*
 * Public-domain 5x7 font — assembly of font5x7.c
 *
 * This file is only data. There is no function, no call0 frame, no ret.
 * C still sees the same symbol:
 *
 *     extern const uint8_t font5x7[96][5];
 *
 * Memory layout (row-major, same as C):
 *   glyph 0 (ASCII 0x20 space): 5 bytes
 *   glyph 1 (ASCII 0x21 '!'):   next 5 bytes
 *   ...
 *   glyph 95 (ASCII 0x7F):      last 5 bytes
 *   total = 96 * 5 = 480 bytes, packed, no padding
 *
 * Each glyph is 5 columns. Each column is one byte. Bit 0 (LSB) is the
 * TOP pixel, bit 6 is the bottom of the 7-row glyph, bit 7 is unused.
 *
 *     column 0        column 1
 *     bit0 = top      bit0 = top
 *     bit1
 *     ...
 *     bit6 = bottom
 *
 * tft_draw_char looks up a character with
 *
 *     col = font5x7[c - 32];          // C: pointer to 5 bytes
 *
 * which in asm is
 *
 *     index  = c - 32                 // space is glyph 0
 *     addr   = font5x7 + index * 5    // 5 bytes per glyph
 *
 * *5 is not a shift. One cheap way on Xtensa:
 *
 *     addi   a3, a2, -32              // a3 = c - 32
 *     addx4  a4, a3, a3               // a4 = a3 + (a3 << 2) = index * 5
 *     add    a4, a4, a5               // a4 = &font5x7[index][0]  (a5 = &font5x7)
 *
 * Then l8ui a6, a4, 0  /  1  /  2  /  3  /  4  loads the five columns.
 */

